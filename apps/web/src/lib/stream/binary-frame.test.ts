import { expect, it } from 'vitest';
import fixture from '../../../../../packages/protocol/fixtures/manifest.json';
import scopedFixtures from '../../../../../packages/protocol/fixtures/scoped-binary-frames.json';
import wireFixture from '../../../../../packages/protocol/fixtures/binary-frame.json';
import { decodeBinaryFrame } from './binary-frame';
import { PoseBuffer } from './pose-buffer';

export function packet(seq = 1n, kind = 2): ArrayBuffer {
  const buffer = new ArrayBuffer(76);
  const view = new DataView(buffer);
  new Uint8Array(buffer, 0, 4).set([78, 83, 89, 78]);
  view.setUint16(4, 1, true);
  view.setUint16(6, kind, true);
  view.setUint32(8, fixture.revisionNumericId, true);
  view.setBigUint64(16, seq, true);
  view.setFloat64(24, 0.125, true);
  view.setFloat64(32, 1000, true);
  view.setUint32(40, 1, true);
  view.setUint32(44, 7, true);
  [1.23456789, -2, 3, 0, 0, 0, 1].forEach((value, i) =>
    view.setFloat32(48 + i * 4, value, true),
  );
  return buffer;
}

it('reads bytes generated by the authoritative Python FrameCodec', () => {
  const bytes = Uint8Array.from(wireFixture.hex.match(/../g)!, (hex) =>
    parseInt(hex, 16),
  );
  const decoded = decodeBinaryFrame(
    bytes.buffer,
    wireFixture.revisionNumericId,
    1,
  )!;
  expect(decoded.type).toBe(wireFixture.frame.type);
  expect(decoded.seq).toBe(wireFixture.frame.seq);
  expect(Array.from(decoded.values.slice(1))).toEqual(
    wireFixture.frame.poses[0].slice(1),
  );
});

it('decodes the fixed NSYN layout without per-body objects and feeds the normal pose buffer', () => {
  const frame = decodeBinaryFrame(packet(), fixture.revisionNumericId, 2)!;
  expect(frame.seq).toBe(1);
  expect(frame.ids[0]).toBe(7);
  expect(frame.values[1]).toBeCloseTo(1.23456789, 6);
  const buffer = new PoseBuffer();
  buffer.configure(fixture as never);
  expect(buffer.pushBinary(packet(), 1100)).toBe(true);
  expect(buffer.readLatest('/World/Arm')!.p).toEqual([
    Math.fround(1.23456789),
    -2,
    3,
  ]);
  expect(buffer.latestSample).toMatchObject({
    seq: 1,
    simTime: 0.125,
    epoch: 0,
  });
});

it('rejects malformed size, magic, version, kind, revision, count, timestamp and unsafe uint64 seq', () => {
  const mutations = [
    (v: DataView) => v.setUint8(0, 0),
    (v: DataView) => v.setUint16(4, 2, true),
    (v: DataView) => v.setUint16(6, 99, true),
    (v: DataView) => v.setUint32(8, 99, true),
    (v: DataView) => v.setUint32(40, 3, true),
    (v: DataView) => v.setFloat64(32, NaN, true),
    (v: DataView) => v.setBigUint64(16, 2n ** 53n, true),
  ];
  for (const mutate of mutations) {
    const bytes = packet();
    mutate(new DataView(bytes));
    expect(
      decodeBinaryFrame(bytes, fixture.revisionNumericId, 2),
    ).toBeUndefined();
  }
  const buffer = new PoseBuffer();
  buffer.configure(fixture as never);
  expect(buffer.pushBinary(packet().slice(0, -1), 1100)).toBe(false);
  expect(buffer.invalidBinaryFrames).toBe(1);
});

it('preserves reset/recovery and finite-pose rules for binary snapshots', () => {
  const buffer = new PoseBuffer();
  buffer.configure(fixture as never);
  buffer.pushBinary(packet(), 1100);
  const invalid = packet(2n, 1);
  new DataView(invalid).setFloat32(48, NaN, true);
  expect(buffer.pushBinary(invalid, 1133)).toBe(true);
  expect(buffer.skippedNonFinite).toBe(1);
  expect(buffer.readLatest('/World/Arm')!.p[0]).toBe(Math.fround(1.23456789));
  const reset = packet(3n);
  new DataView(reset).setUint32(12, 1, true);
  expect(buffer.pushBinary(reset, 1200)).toBe(true);
  expect(buffer.epoch).toBe(1);
  buffer.expectSnapshot();
  expect(buffer.pushBinary(reset, 5000)).toBe(true);
  expect(buffer.pushBinary(packet(2n, 1), 5010)).toBe(false);
});

it('decodes Python scoped snapshot/full/delta bytes with explicit pose and removal bounds', () => {
  const buffer = new PoseBuffer();
  buffer.configure(fixture as never);
  buffer.acceptSubscription(3);
  for (const [i, sample] of scopedFixtures.entries()) {
    const bytes = Uint8Array.from(sample.hex.match(/../g)!, (hex) =>
      parseInt(hex, 16),
    ).buffer;
    const decoded = decodeBinaryFrame(bytes, 1, 1)!;
    expect(decoded.type).toBe(sample.frame.type);
    expect(decoded.subscriptionId).toBe(3);
    expect(decoded.ids.length).toBe(sample.frame.poses.length * 8);
    expect(buffer.pushBinary(bytes, 2000 + i * 20)).toBe(true);
    if (
      sample.frame.type === 'transform.delta' &&
      sample.frame.removedStreamIds?.length
    ) {
      expect(Array.from(decoded.removedStreamIds!)).toEqual([7]);
      expect(buffer.readLatest('/World/Arm')).toBeUndefined();
    } else
      expect(buffer.readLatest('/World/Arm')!.p).toEqual(
        sample.frame.poses[0].slice(1, 4),
      );
    expect(decodeBinaryFrame(bytes.slice(0, -1), 1, 1)).toBeUndefined();
  }
  expect(buffer.frameCount).toBe(4);
  const invalid = Uint8Array.from(scopedFixtures[1].hex.match(/../g)!, (hex) =>
    parseInt(hex, 16),
  ).buffer;
  new DataView(invalid).setBigUint64(48, 11n, true);
  expect(decodeBinaryFrame(invalid, 1, 1)).toBeUndefined();
});

it('holds the previous valid binary delta value without replacing cumulative baseline semantics', () => {
  const buffer = new PoseBuffer();
  buffer.configure(fixture as never);
  buffer.acceptSubscription(3);
  const fromHex = (hex: string) =>
    Uint8Array.from(hex.match(/../g)!, (value) => parseInt(value, 16)).buffer;
  buffer.pushBinary(fromHex(scopedFixtures[0].hex), 1000);
  buffer.pushBinary(fromHex(scopedFixtures[2].hex), 1020);
  const invalid = fromHex(scopedFixtures[2].hex);
  new DataView(invalid).setBigUint64(16, 13n, true);
  new DataView(invalid).setFloat32(64, NaN, true);
  buffer.pushBinary(invalid, 1040);
  expect(buffer.readLatest('/World/Arm')!.p).toEqual([9, 8, 7]);
  expect(buffer.skippedNonFinite).toBe(1);
});
