"""Deterministic procedural packages for the Scene Factory's missing static props.

The rack is a six-hole test-tube rack. Version 1 deliberately uses one solid
collision box while its visual already shows holes; version 2 keeps the same
visual and replaces the collision with real base, wall and top-plate colliders
that leave a clearance opening around each hole. Both versions are generated
here so the tube-seat failure and its repair are reproducible and separate
immutable asset versions.

Nothing in this module imports Blender. The canonical asset and browser visual
bytes are produced by the pure factory; Blender only receives the same mesh
description for visual authoring.
"""

from __future__ import annotations

import hashlib
import json
import math
from dataclasses import dataclass

import trimesh
import yaml
from trimesh.visual.material import PBRMaterial

SCHEMA = "lw.procedural-asset/1"
LICENSE_TEXT = (
    "CC0-1.0 (https://creativecommons.org/publicdomain/zero/1.0/)\n"
    "Self-authored procedural geometry and materials generated by factory/procedural.py "
    "for spatial-sync. No third-party asset bytes are included.\n"
)
COLORS = {
    "rack": [46, 92, 128, 255],
    "tube": [146, 196, 214, 255],
}


class ProceduralError(ValueError):
    """The declared procedural parameters cannot produce a supported package."""


@dataclass(frozen=True)
class Box:
    name: str
    center: tuple[float, float, float]
    size: tuple[float, float, float]

    @property
    def half(self):
        return tuple(value / 2 for value in self.size)


@dataclass(frozen=True)
class Rack:
    params: dict
    sites: tuple[tuple[str, float, float], ...]
    visual: tuple[Box, ...]
    collision: tuple[Box, ...]
    volume_m3: float
    mass_kg: float
    dimensions_m: tuple[float, float, float]


@dataclass(frozen=True)
class Tube:
    params: dict
    radius_m: float
    height_m: float
    mass_kg: float
    dimensions_m: tuple[float, float, float]


def _positive(name, value):
    if not isinstance(value, (int, float)) or isinstance(value, bool) or not math.isfinite(value):
        raise ProceduralError(f"{name} must be a finite number")
    if value <= 0:
        raise ProceduralError(f"{name} must be positive")
    return float(value)


def _axis_bands(centers, half, hole_half):
    start = -half
    bands = []
    for center in centers:
        bands.append((start, center - hole_half))
        start = center + hole_half
    bands.append((start, half))
    return [(low, high) for low, high in bands if high - low > 1e-9]


def rack_layout(params):
    """Return the validated hole layout and non-overlapping top-plate tiles."""
    width = _positive("widthM", params["widthM"])
    depth = _positive("depthM", params["depthM"])
    height = _positive("heightM", params["heightM"])
    wall = _positive("wallThicknessM", params["wallThicknessM"])
    base = _positive("baseThicknessM", params["baseThicknessM"])
    top = _positive("plateThicknessM", params["plateThicknessM"])
    hole = _positive("holeDiameterM", params["holeDiameterM"])
    tube = _positive("tubeDiameterM", params["tubeDiameterM"])
    clearance = _positive("clearanceM", params["clearanceM"])
    pitch_x = _positive("pitchXM", params["pitchXM"])
    pitch_y = _positive("pitchYM", params["pitchYM"])
    rows, columns = params["rows"], params["columns"]
    if rows != 2 or columns != 3:
        raise ProceduralError("the six-hole rack requires rows: 2 and columns: 3")
    for name in ("rows", "columns"):
        if isinstance(params[name], bool) or not isinstance(params[name], int):
            raise ProceduralError(f"{name} must be an integer")
    if hole < tube + 2 * clearance - 1e-12:
        raise ProceduralError("holeDiameterM must provide the declared clearance around the tube")
    if not (wall < width / 2 and wall < depth / 2):
        raise ProceduralError("wallThicknessM must be smaller than half the rack footprint")
    if base + top >= height:
        raise ProceduralError("baseThicknessM + plateThicknessM must leave wall height")
    if pitch_x <= hole or pitch_y <= hole:
        raise ProceduralError("hole pitch must exceed the hole diameter")
    centers_x = [(-(columns - 1) / 2 + index) * pitch_x for index in range(columns)]
    centers_y = [(-(rows - 1) / 2 + index) * pitch_y for index in range(rows)]
    half_x, half_y, hole_half = width / 2, depth / 2, hole / 2
    for center in centers_x:
        if abs(center) + hole_half + wall > half_x + 1e-12:
            raise ProceduralError("hole layout does not fit inside the rack width")
    for center in centers_y:
        if abs(center) + hole_half + wall > half_y + 1e-12:
            raise ProceduralError("hole layout does not fit inside the rack depth")
    sites = tuple(
        (f"Hole{chr(ord('A') + row)}{column + 1}", centers_x[column], centers_y[row])
        for row in range(rows)
        for column in range(columns)
    )
    return {
        "width": width,
        "depth": depth,
        "height": height,
        "wall": wall,
        "base": base,
        "top": top,
        "hole": hole,
        "centersX": centers_x,
        "centersY": centers_y,
        "sites": sites,
    }


def rack_boxes(params):
    layout = rack_layout(params)
    width, depth, height = layout["width"], layout["depth"], layout["height"]
    wall, base, top = layout["wall"], layout["base"], layout["top"]
    inner_height = height - base - top
    boxes = [
        Box("Base", (0.0, 0.0, base / 2), (width, depth, base)),
        Box("WallLeft", (-width / 2 + wall / 2, 0.0, base + inner_height / 2), (wall, depth, inner_height)),
        Box("WallRight", (width / 2 - wall / 2, 0.0, base + inner_height / 2), (wall, depth, inner_height)),
        Box(
            "WallBack",
            (0.0, depth / 2 - wall / 2, base + inner_height / 2),
            (width - 2 * wall, wall, inner_height),
        ),
        Box(
            "WallFront",
            (0.0, -depth / 2 + wall / 2, base + inner_height / 2),
            (width - 2 * wall, wall, inner_height),
        ),
    ]
    top_z = height - top / 2
    hole_half = layout["hole"] / 2
    y_bands = _axis_bands(layout["centersY"], depth / 2, hole_half)
    x_bands = _axis_bands(layout["centersX"], width / 2, hole_half)
    index = 0
    for low, high in y_bands:
        boxes.append(Box(f"Top{index}", (0.0, (low + high) / 2, top_z), (width, high - low, top)))
        index += 1
    for row, center_y in enumerate(layout["centersY"]):
        for low, high in x_bands:
            boxes.append(
                Box(
                    f"Top{index}",
                    ((low + high) / 2, center_y, top_z),
                    (high - low, 2 * hole_half, top),
                )
            )
            index += 1
    return tuple(boxes)


def rack_geometry(params) -> Rack:
    layout = rack_layout(params)
    visual = rack_boxes(params)
    solid = Box(
        "Collision",
        (0.0, 0.0, layout["height"] / 2),
        (layout["width"], layout["depth"], layout["height"]),
    )
    collision = (solid,) if params["collision"] == "solid" else visual
    if params["collision"] not in ("solid", "holes"):
        raise ProceduralError("collision must be 'solid' or 'holes'")
    density = _positive("massDensityKgM3", params["massDensityKgM3"])
    volume = sum(box.size[0] * box.size[1] * box.size[2] for box in collision)
    mass = round(volume * density, 9)
    return Rack(
        params=dict(params),
        sites=layout["sites"],
        visual=visual,
        collision=collision,
        volume_m3=volume,
        mass_kg=mass,
        dimensions_m=(layout["width"], layout["depth"], layout["height"]),
    )


def tube_geometry(params) -> Tube:
    diameter = _positive("diameterM", params["diameterM"])
    height = _positive("heightM", params["heightM"])
    density = _positive("massDensityKgM3", params["massDensityKgM3"])
    radius = diameter / 2
    volume = math.pi * radius * radius * height
    return Tube(
        params=dict(params),
        radius_m=radius,
        height_m=height,
        mass_kg=round(volume * density, 9),
        dimensions_m=(diameter, diameter, height),
    )


def mesh_json(mesh):
    return {
        "vertices": [[round(float(value), 9) for value in vertex] for vertex in mesh.vertices],
        "faces": [[int(index) for index in face] for face in mesh.faces],
    }


def rack_mesh(params):
    scene = trimesh.Scene()
    for box in rack_boxes(params):
        part = trimesh.creation.box(extents=box.size)
        part.apply_translation(box.center)
        part.visual = trimesh.visual.TextureVisuals(
            material=PBRMaterial(
                baseColorFactor=COLORS["rack"], metallicFactor=0.05, roughnessFactor=0.7
            )
        )
        scene.add_geometry(part, node_name=box.name)
    return scene


def tube_mesh(params):
    geometry = tube_geometry(params)
    mesh = trimesh.creation.cylinder(radius=geometry.radius_m, height=geometry.height_m, sections=32)
    mesh.apply_translation((0.0, 0.0, geometry.height_m / 2))
    mesh.visual = trimesh.visual.TextureVisuals(
        material=PBRMaterial(baseColorFactor=COLORS["tube"], metallicFactor=0.0, roughnessFactor=0.3)
    )
    return mesh


def rack_mesh_json(params):
    """One combined triangle mesh for Blender visual authoring."""
    return mesh_json(trimesh.util.concatenate([part for part in rack_mesh(params).geometry.values()]))


def tube_mesh_json(params):
    return mesh_json(tube_mesh(params))


def _number(value):
    text = f"{float(value):.9g}"
    return "0" if text == "-0" else text


def _vec(values):
    return "(" + ", ".join(_number(value) for value in values) + ")"


def _cube(name, box: Box, indent):
    pad = " " * indent
    return (
        f'{pad}def Cube "{name}" (\n'
        f'{pad}    prepend apiSchemas = ["PhysicsCollisionAPI"]\n'
        f"{pad})\n"
        f"{pad}{{\n"
        f"{pad}    double size = 1\n"
        f"{pad}    float3 xformOp:scale = {_vec(box.size)}\n"
        f"{pad}    double3 xformOp:translate = {_vec(box.center)}\n"
        f'{pad}    uniform token[] xformOpOrder = ["xformOp:scale", "xformOp:translate"]\n'
        f"{pad}}}\n"
    )


def _rack_inertia(mass, width, depth, height):
    return (
        mass * (depth * depth + height * height) / 12,
        mass * (width * width + height * height) / 12,
        mass * (width * width + depth * depth) / 12,
    )


def _tube_inertia(mass, radius, height):
    cross = mass * (3 * radius * radius + height * height) / 12
    return cross, cross, mass * radius * radius / 2


def _usd_header():
    return (
        "#usda 1.0\n"
        "(\n"
        '    defaultPrim = "Asset"\n'
        "    metersPerUnit = 1\n"
        '    upAxis = "Z"\n'
        ")\n\n"
    )


def rack_usd(params):
    geometry = rack_geometry(params)
    width, depth, height = geometry.dimensions_m
    inertia = _rack_inertia(geometry.mass_kg, width, depth, height)
    text = _usd_header()
    text += (
        'def Xform "Asset" (\n'
        '    prepend apiSchemas = ["PhysicsRigidBodyAPI", "PhysicsMassAPI"]\n'
        ")\n"
        "{\n"
        "    bool physics:kinematicEnabled = true\n"
        f"    float physics:mass = {_number(geometry.mass_kg)}\n"
        f"    float3 physics:diagonalInertia = {_vec(inertia)}\n"
        f"    point3f physics:centerOfMass = {_vec((0, 0, height / 2))}\n"
    )
    for box in geometry.collision:
        text += _cube(box.name, box, 4)
    for name, x, y in geometry.sites:
        text += (
            f'    def Xform "{name}"\n'
            "    {\n"
            f"        double3 xformOp:translate = {_vec((x, y, params['baseThicknessM']))}\n"
            '        uniform token[] xformOpOrder = ["xformOp:translate"]\n'
            "    }\n"
        )
    return text + "}\n"


def tube_usd(params):
    geometry = tube_geometry(params)
    inertia = _tube_inertia(geometry.mass_kg, geometry.radius_m, geometry.height_m)
    return (
        _usd_header()
        + 'def Xform "Asset" (\n'
        '    prepend apiSchemas = ["PhysicsRigidBodyAPI", "PhysicsMassAPI"]\n'
        ")\n"
        "{\n"
        f"    float physics:mass = {_number(geometry.mass_kg)}\n"
        f"    float3 physics:diagonalInertia = {_vec(inertia)}\n"
        f"    point3f physics:centerOfMass = {_vec((0, 0, geometry.height_m / 2))}\n"
        '    def Cylinder "Glass" (\n'
        '        prepend apiSchemas = ["PhysicsCollisionAPI"]\n'
        "    )\n"
        "    {\n"
        f"        double radius = {_number(geometry.radius_m)}\n"
        f"        double height = {_number(geometry.height_m)}\n"
        '        uniform token axis = "Z"\n'
        f"        double3 xformOp:translate = {_vec((0, 0, geometry.height_m / 2))}\n"
        '        uniform token[] xformOpOrder = ["xformOp:translate"]\n'
        "    }\n"
        "}\n"
    )


def _files_digest(files):
    digest = hashlib.sha256()
    for name in sorted(files):
        digest.update(name.encode("utf-8") + b"\0")
        digest.update(hashlib.sha256(files[name]).digest())
    return digest.hexdigest()


def _package_files(identifier, kind, title, description, stage, visual, dimensions, physics, extra, payload):
    metadata = {
        "id": identifier,
        "kind": kind,
        "title": title,
        "description": description,
        "stage": stage,
        "visual": visual,
        "dimensionsM": list(dimensions),
        "physics": physics,
        "dressing": False,
    }
    metadata.update(extra)
    files = {
        "asset.yaml": yaml.safe_dump(metadata, sort_keys=True, allow_unicode=True).encode("utf-8"),
        "LICENSE": LICENSE_TEXT.encode("utf-8"),
    }
    files.update(payload)
    provenance = {
        "schema": SCHEMA,
        "source": "factory/procedural.py",
        "license": "CC0-1.0",
        "recipe": "sf3-procedural-v1",
        "approximations": [
            "Mass is nominal density times the authored collision volume; it is not measured.",
            "Inertia uses the solid bounding-box or cylinder formula, not a measured tensor.",
        ],
        "files": {
            name: {"sha256": hashlib.sha256(value).hexdigest(), "bytes": len(value)}
            for name, value in files.items()
        },
    }
    files["provenance.json"] = (json.dumps(provenance, indent=2, sort_keys=True) + "\n").encode()
    return files


def rack_package(spec):
    params = dict(spec["rack"])
    geometry = rack_geometry(params)
    files = _package_files(
        spec["id"],
        spec["kind"],
        "Six-hole test-tube rack",
        (
            "Procedural six-hole test-tube rack. Version 1 uses a solid collision box; "
            "version 2 collision leaves the authored hole clearance."
            if params["collision"] == "solid"
            else "Procedural six-hole test-tube rack with hole and clearance collision."
        ),
        "asset.usda",
        "visual.glb",
        geometry.dimensions_m,
        {
            "massKg": geometry.mass_kg,
            "massSource": "estimated",
            "collision": "authored",
        },
        {},
        {
            "asset.usda": rack_usd(params).encode("utf-8"),
            "visual.glb": rack_mesh(params).export(file_type="glb"),
        },
    )
    return files, geometry


def tube_package(spec):
    params = dict(spec["tube"])
    geometry = tube_geometry(params)
    files = _package_files(
        spec["id"],
        spec["kind"],
        "Procedural test tube",
        "Procedural 30 mm test tube with an authored cylinder collision and dynamic body.",
        "asset.usda",
        "visual.glb",
        geometry.dimensions_m,
        {
            "massKg": geometry.mass_kg,
            "massSource": "estimated",
            "collision": "authored",
        },
        {
            "implements": [
                {
                    "type": "tube/v1",
                    "programs": {"newton": "tube.newton"},
                    "config": {"robots": []},
                }
            ]
        },
        {
            "asset.usda": tube_usd(params).encode("utf-8"),
            "visual.glb": tube_mesh(params).export(file_type="glb"),
        },
    )
    return files, geometry


def package_digest(files):
    return _files_digest(files)
