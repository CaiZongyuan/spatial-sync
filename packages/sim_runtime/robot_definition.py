"""Pure labels and input data consumed by the FR3 builder and structure inspector."""

from pathlib import Path, PurePosixPath
from xml.etree import ElementTree

from .sites import anchor_label

ROBOT_PREFIX = "World/Lab/RobotA"
ROBOT_FLOATING = False
ASSET = Path(__file__).resolve().parents[2] / "assets/robots/franka_emika_panda/urdf/fr3_franka_hand.urdf"
RACK_POINTS = [
    (f"{row}{column + 1}", (-0.17 + 0.055 * column, -0.25 + 0.12 * r, 0.84))
    for r, row in enumerate("AB")
    for column in range(4)
]
ROTOR_CENTER = (0.06, 0.20, 0.85)
SLOT_OFFSETS = [(0.045, 0, 0.02), (0, 0.045, 0.02), (-0.045, 0, 0.02), (0, -0.045, 0.02)]
TUBES = tuple(f"World/Lab/Tubes/Tube{index + 1:02d}" for index in range(20))
RACK_SITES = tuple("World/Lab/Rack/" + name for name, _ in RACK_POINTS)
SLOT_SITES = tuple(f"World/Lab/Centrifuge/Rotor/Slot{index + 1}" for index in range(len(SLOT_OFFSETS)))
ROTOR, SPINDLE = "World/Lab/Centrifuge/Rotor", "World/Lab/Centrifuge/Spindle"
LID, LID_JOINT = "World/Lab/Centrifuge/Lid", "World/Lab/Centrifuge/LidHinge"
LID_LIMITS = (0, 1.4)
TCP = "fr3/fr3_hand/tcp"
FLOOR, WORKBENCH_TOP, RACK_PLATE, HOUSING = (
    "World/Lab/Floor",
    "World/Lab/Workbench/Top",
    "World/Lab/Rack/Plate",
    "World/Lab/Centrifuge/Housing",
)
WORKBENCH_LEGS = tuple(
    (f"World/Lab/Workbench/Leg{index + 1}", point)
    for index, point in enumerate(((-1.1, -0.65), (-1.1, 0.65), (1.7, -0.65), (1.7, 0.65)))
)


def slot_geometry_labels(prefix):
    return prefix + "/Support", tuple(prefix + f"/Guide{side + 1}" for side in (-1, 1))


def structure():
    urdf = ElementTree.parse(ASSET).getroot()
    prefix = "/" + ROBOT_PREFIX + "/" + urdf.attrib["name"] + "/"
    bodies = {prefix + link.attrib["name"] for link in urdf.findall("link")}
    bodies.update("/" + label for label in (*TUBES, ROTOR, LID, *(site + "Body" for site in SLOT_SITES)))
    joints = {}
    for joint in urdf.findall("joint"):
        kind = joint.attrib["type"]
        limit = joint.find("limit")
        joints[prefix + joint.attrib["name"]] = {
            "kind": kind,
            "limits": [float(limit.attrib["lower"]), float(limit.attrib["upper"])]
            if kind in ("revolute", "prismatic") and limit is not None
            else None,
        }
    # These identities are generated by the pinned Newton 1.7 URDF/add_body importers.
    if not ROBOT_FLOATING:
        joints[prefix + "fixed_base"] = {"kind": "fixed", "limits": None}
    joints.update({"/" + label + "_free_joint": {"kind": "free", "limits": None} for label in TUBES})
    joints["/" + SPINDLE] = {"kind": "revolute", "limits": None}
    joints["/" + LID_JOINT] = {"kind": "revolute", "limits": LID_LIMITS}
    joints.update({"/" + site + "Mount": {"kind": "fixed", "limits": None} for site in SLOT_SITES})
    sites = {"/" + label for label in (*RACK_SITES, *SLOT_SITES, ROBOT_PREFIX + "/" + TCP)}
    sites.update(anchor_label(key) for key, value in joints.items() if value["kind"] != "free")
    entities = bodies | {"/" + name for name in (FLOOR, WORKBENCH_TOP, RACK_PLATE, HOUSING)}
    entities.update("/" + label for label, _ in WORKBENCH_LEGS)
    for site in RACK_SITES:
        support, guides = slot_geometry_labels(site + "Geometry")
        entities.update("/" + label for label in (support, *guides))
    entities.update(str(parent) for key in tuple(entities) for parent in PurePosixPath(key).parents)
    entities.discard("/")
    return {"entities": sorted(entities), "bodies": sorted(bodies), "sites": sorted(sites), "joints": joints}
