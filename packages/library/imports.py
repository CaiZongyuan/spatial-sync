"""Both package kinds share one confined upload and immutable publication transaction."""

import json
import tempfile
from pathlib import Path

from packages.library.archive import destination_parent, extract_package, import_lock, invalid
from packages.library.common import content_hash
from packages.library.metadata import asset_metadata, scene_metadata


class LibraryImports:
    def __init__(self, assets, scenes, validator):
        self.assets, self.scenes, self.validator = assets, scenes, validator

    def import_tar(self, stream):
        root = self.assets.roots["user"]
        root.mkdir(parents=True, exist_ok=True)
        with tempfile.TemporaryDirectory(prefix=".import-", dir=root) as temporary:
            stage = Path(temporary) / "package"
            stage.mkdir()
            extract_package(stream, stage)
            manifests = {entry.name for entry in stage.iterdir()}
            if "asset.yaml" in manifests and "scene.yaml" not in manifests:
                kind, data, bindings, locations = "asset", asset_metadata(stage), None, None
                bare_id, collection = data["id"], self.assets
            elif "scene.yaml" in manifests and "asset.yaml" not in manifests:
                data, bindings, locations = scene_metadata(stage)
                kind, bare_id, collection = "scene", data["name"], self.scenes
            else:
                path = next(
                    (
                        entry.casefold()
                        for entry in manifests
                        if entry.casefold() in ("asset.yaml", "scene.yaml")
                    ),
                    "metadata",
                )
                raise invalid("Provide exactly one correctly named asset.yaml or scene.yaml", path=path)
            upload_hash = content_hash(stage)
            parents = ("assets", *bare_id.split("/")) if kind == "asset" else ("scenes", bare_id)
            with self.assets._lock, import_lock(root):
                destination_parent(root, parents)
                self.assets.startup()
                self.scenes.refresh()
                existing = next(
                    (
                        version
                        for version in collection.versions.values()
                        if (version.bare_id if kind == "asset" else version.name) == bare_id
                        and upload_hash
                        in (version.content_hash, (version.validation or {}).get("importContentHash"))
                    ),
                    None,
                )
                if existing is not None:
                    return self.assets._complete(existing, True, kind=kind)
                if (stage / "validation.json").exists():
                    raise invalid(
                        "validation.json is generated by the gateway; omit it from a new package",
                        path="validation.json",
                    )
                revision = 1 + max(
                    (
                        version.rev
                        for version in collection.versions.values()
                        if (version.bare_id if kind == "asset" else version.name) == bare_id
                    ),
                    default=0,
                )
                report = self.validator.run(
                    stage, kind, f"{kind}:{bare_id}@{revision}", data, self.assets, bindings, locations
                ) | {"importContentHash": upload_hash}
                (stage / "validation.json").write_text(
                    json.dumps(report, allow_nan=False, indent=2) + "\n", encoding="utf-8"
                )
                destination = destination_parent(root, parents, create=True) / str(revision)
                if destination.exists() or destination.is_symlink() or destination.is_junction():
                    raise invalid("Revision destination already exists")
                stage.rename(destination)
                self.assets.startup()
                self.scenes.refresh()
                return self.assets._complete(collection.versions[f"{bare_id}@{revision}"], False, kind=kind)
