"""Both package kinds share one confined upload and immutable publication transaction."""

import json
import os
import tempfile
from dataclasses import dataclass
from pathlib import Path

from packages.library.archive import (
    destination_parent,
    extract_package,
    import_lock,
    invalid,
    package_files,
)
from packages.library.common import content_hash
from packages.library.metadata import asset_metadata, scene_metadata
from packages.library.transactions import reserve_revision, revisions

# The public upload boundary stays at 128 MiB / 256 MiB. A server-staged package
# (already owned by the acquisition worker) may be larger, but remains bounded
# by the same SF2 adapted-package budget.
INTERNAL_MAX_BYTES = 512 * 1024 * 1024
INTERNAL_MAX_FILES = 4096
COPY_BLOCK_BYTES = 1024 * 1024


@dataclass(frozen=True)
class StagedLimits:
    max_bytes: int = INTERNAL_MAX_BYTES
    max_files: int = INTERNAL_MAX_FILES


class LibraryImports:
    def __init__(self, assets, scenes, validator):
        self.assets, self.scenes, self.validator = assets, scenes, validator

    def import_tar(self, stream):
        root = self.assets.roots["user"]
        root.mkdir(parents=True, exist_ok=True)
        with tempfile.TemporaryDirectory(prefix=".import-", dir=root) as temporary:
            stage = Path(temporary) / "package"
            stage.mkdir()
            extract_package(stream, stage)
            return self._publish(stage)

    def import_staged(self, path, *, allowed_root, limits=None):
        """Publish a package directory that only the server itself staged.

        The caller never supplies a browser path or URL: ``allowed_root`` is
        operator configuration and every entry below it is re-confined here.
        """
        limits = limits or StagedLimits()
        stage = confined_stage(path, allowed_root, limits)
        root = self.assets.roots["user"]
        root.mkdir(parents=True, exist_ok=True)
        if stage.is_relative_to(root.resolve()):
            # The acquisition stage already lives on the library filesystem;
            # publish in place so peak disk stays source cache + adapted stage.
            return self._publish(stage)
        with tempfile.TemporaryDirectory(prefix=".import-", dir=root) as temporary:
            copy = Path(temporary) / "package"
            copy.mkdir()
            copy_stage(stage, copy, limits)
            return self._publish(copy)

    def _publish(self, stage):
        manifests = {entry.name for entry in stage.iterdir()}
        if "asset.yaml" in manifests and "scene.yaml" not in manifests:
            kind, data, bindings, locations = "asset", asset_metadata(stage), None, None
            bare_id, collection = data["id"], self.assets
        elif "scene.yaml" in manifests and "asset.yaml" not in manifests:
            data, bindings, locations = scene_metadata(stage)
            kind, bare_id, collection = "scene", data["name"], self.scenes
        else:
            path = next(
                (
                    entry.casefold()
                    for entry in manifests
                    if entry.casefold() in ("asset.yaml", "scene.yaml")
                ),
                "metadata",
            )
            raise invalid("Provide exactly one correctly named asset.yaml or scene.yaml", path=path)
        root = self.assets.roots["user"]
        upload_hash = content_hash(stage)
        parents = ("assets", *bare_id.split("/")) if kind == "asset" else ("scenes", bare_id)
        with self.assets._lock, import_lock(root):
            destination_parent(root, parents)
            self.assets.startup()
            self.scenes.refresh()
            existing = next(
                (
                    version
                    for version in collection.versions.values()
                    if (version.bare_id if kind == "asset" else version.name) == bare_id
                    and upload_hash
                    in (version.content_hash, (version.validation or {}).get("importContentHash"))
                ),
                None,
            )
            if existing is not None:
                return self.assets._complete(existing, True, kind=kind)
            if (stage / "validation.json").exists():
                raise invalid(
                    "validation.json is generated by the gateway; omit it from a new package",
                    path="validation.json",
                )
            revision = 1 + max(
                (
                    version.rev
                    for version in collection.versions.values()
                    if (version.bare_id if kind == "asset" else version.name) == bare_id
                ),
                default=0,
            )
            revision = max(revision, 1 + revisions(root).get(f"{kind}:{bare_id}", 0))
            report = self.validator.run(
                stage, kind, f"{kind}:{bare_id}@{revision}", data, self.assets, bindings, locations
            ) | {"importContentHash": upload_hash}
            (stage / "validation.json").write_text(
                json.dumps(report, allow_nan=False, indent=2) + "\n", encoding="utf-8"
            )
            destination = destination_parent(root, parents, create=True) / str(revision)
            if destination.exists() or destination.is_symlink() or destination.is_junction():
                raise invalid("Revision destination already exists")
            reserve_revision(root, f"{kind}:{bare_id}", revision)
            stage.rename(destination)
            self.assets.startup()
            self.scenes.refresh()
            return self.assets._complete(collection.versions[f"{bare_id}@{revision}"], False, kind=kind)


def confined_stage(path, allowed_root, limits):
    """Return the resolved stage directory after rejecting links and escapes."""
    root = Path(os.path.abspath(allowed_root))
    candidate = Path(os.path.abspath(path))
    try:
        relative = candidate.relative_to(root)
    except ValueError:
        raise invalid("Staged package must stay inside the acquisition staging root") from None
    if not relative.parts:
        raise invalid("Staged package must be a directory below the staging root")
    if root.is_symlink() or root.is_junction() or not root.is_dir():
        raise invalid("Staging root is unavailable")
    current = root
    for part in relative.parts:
        current = current / part
        if current.is_symlink() or current.is_junction():
            raise invalid("Staged package contains a filesystem link")
    if not candidate.is_dir():
        raise invalid("Staged package must be a directory")
    stage = candidate.resolve(strict=True)
    if not stage.is_relative_to(root.resolve(strict=True)) or stage == root.resolve(strict=True):
        raise invalid("Staged package must stay inside the acquisition staging root")
    try:
        files = package_files(stage)
    except (OSError, ValueError) as exc:
        raise invalid(str(exc)) from None
    if any(entry.name.casefold() == "validation.json" for entry in stage.iterdir()):
        raise invalid(
            "validation.json is generated by the gateway; omit it from a staged package",
            path="validation.json",
        )
    if len(files) > limits.max_files:
        raise invalid(f"Staged package exceeds {limits.max_files} files")
    total = 0
    for name in files:
        total += (stage / name).stat().st_size
        if total > limits.max_bytes:
            raise invalid(f"Staged package exceeds {limits.max_bytes} bytes")
    return stage


def copy_stage(stage, target, limits):
    """Copy a verified stage under a freshly allocated temporary directory."""
    remaining = limits.max_bytes
    try:
        for entry in sorted(stage.rglob("*")):
            relative = entry.relative_to(stage)
            destination = target / relative
            if (
                entry.is_symlink()
                or entry.is_junction()
                or not entry.resolve().is_relative_to(stage)
            ):
                raise invalid("Staged package contains a filesystem link")
            if entry.is_dir():
                destination.mkdir(parents=True, exist_ok=True)
            elif entry.is_file():
                destination.parent.mkdir(parents=True, exist_ok=True)
                with entry.open("rb") as source, destination.open("xb") as output:
                    while chunk := source.read(COPY_BLOCK_BYTES):
                        remaining -= len(chunk)
                        if remaining < 0:
                            raise invalid(f"Staged package exceeds {limits.max_bytes} bytes")
                        output.write(chunk)
            else:
                raise invalid("Staged package contains a nonregular file")
        package_files(target)
    except (OSError, ValueError) as exc:
        raise invalid(str(exc)) from None
